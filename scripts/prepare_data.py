"""Convert the curated CSV into an idempotent SQL seed and a public demo subset."""
import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAPPING = {
    'id': 'id', 'simplified chinese': 'chinese', 'english': 'english',
    'category layer 1': 'category_l1', 'category layer 2': 'category_l2',
    'priority': 'priority', 'example sentence in english': 'example_en',
    'example sentence chinese translation': 'example_zh',
    'part of speech': 'part_of_speech', 'is idiom': 'is_idiom',
    'is slang': 'is_slang', 'pronunciation': 'pronunciation',
}

def sql_literal(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    return "'" + value.replace("'", "''") + "'"

def main():
    with (ROOT / 'chinese_to_english_game.csv').open(encoding='utf-8-sig', newline='') as f:
        rows = [{target: row[source] for source, target in MAPPING.items()} for row in csv.DictReader(f)]
    for row in rows:
        row['id'], row['priority'] = int(row['id']), int(row['priority'])
        row['is_idiom'], row['is_slang'] = row['is_idiom'] == '1', row['is_slang'] == '1'
    assert len({r['id'] for r in rows}) == len(rows)
    columns = list(MAPPING.values())
    update = ', '.join(f'{column} = excluded.{column}' for column in columns if column != 'id')
    parts = ['-- Generated by python3 scripts/prepare_data.py. Run AFTER schema.sql.', 'begin;']
    for start in range(0, len(rows), 200):
        values = ',\n'.join('(' + ', '.join(sql_literal(row[col]) for col in columns) + ')' for row in rows[start:start + 200])
        parts.append(f"insert into public.vocabulary ({', '.join(columns)}) values\n{values}\non conflict (id) do update set {update};")
    parts.append('commit;')
    (ROOT / 'supabase' / 'seed.sql').write_text('\n\n'.join(parts) + '\n', encoding='utf-8')
    # Sample across topics, not just the first food entries; include both expression sets.
    topics = defaultdict(list)
    for row in rows:
        if not row['is_idiom'] and not row['is_slang']:
            topics[row['category_l1']].append(row)
    demo = [row for group in topics.values() for row in group[:3]]
    for flag in ('is_idiom', 'is_slang'):
        demo.extend([row for row in rows if row[flag]][:10])
    # A few longer prompts and less common items exercise filters and mobile layout.
    demo.extend(row for row in rows if row['english'] in {
        'every cloud has a silver lining', 'high-key', 'no cap', 'pissed off',
    })
    assert len({r['id'] for r in demo}) == len(demo)
    (ROOT / 'public' / 'demo-vocabulary.json').write_text(json.dumps(demo, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Prepared {len(rows)} SQL entries and {len(demo)} demo entries.')

if __name__ == '__main__':
    main()
